const CACHE = 'findex-__CACHE_VERSION__';
const ASSETS = __PRECACHE__;
self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(ASSETS.map(url => new Request(url, { cache: 'reload' })))).then(() => self.skipWaiting()));
});
self.addEventListener('activate', event => {
  event.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(key => key.startsWith('findex-') && key !== CACHE).map(key => caches.delete(key)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', event => {
  if (event.request.method !== 'GET') return;
  const url = new URL(event.request.url);
  if (url.origin !== self.location.origin) return;
  if (event.request.mode === 'navigate') {
    event.respondWith(fetch(event.request).catch(() => caches.open(CACHE).then(cache => cache.match('/'))));
    return;
  }
  if (ASSETS.includes(url.pathname)) {
    event.respondWith(caches.open(CACHE).then(async cache => (await cache.match(url.pathname)) || fetch(event.request)));
  }
});

// All push payloads are generated by the authenticated Convex backend. Never
// navigate to a URL from a payload, and always display user-visible web pushes.
self.addEventListener('push', event => {
  event.waitUntil((async () => {
    let data;
    try { data = event.data?.json(); } catch { return; }
    if (!data || typeof data.title !== 'string' || typeof data.body !== 'string') return;
    await self.registration.showNotification(data.title.slice(0, 120), {
      body: data.body.slice(0, 200), icon: '/icons/icon-192.png',
      badge: '/icons/icon-192.png', tag: `findex-${String(data.tag || 'catch').slice(0, 100)}`,
    });
  })());
});
self.addEventListener('notificationclick', event => {
  event.notification.close();
  event.waitUntil((async () => {
    const windows = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
    const target = windows.find(client => new URL(client.url).origin === self.location.origin);
    if (target) { await target.focus(); target.postMessage({ type: 'OPEN_FRIENDS' }); }
    else await self.clients.openWindow('/#friends');
  })());
});
